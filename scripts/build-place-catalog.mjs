#!/usr/bin/env node
/**
 * Builds the global place catalog used by the lab's place-context generators.
 *
 * Canonical sources live in web/profile-viewer/:
 *   place-catalog.js           hand-written UMD engine (window.AepPlaceCatalog / module.exports)
 *   place-catalog-data.json    generated: Natural Earth populated places (pop >= 10k)
 *   place-catalog-data.js      generated: browser wrapper (window.AepPlaceCatalogData)
 *
 * The MCP container only ships tools/aep-lab-profile-mcp/src, so the engine and
 * data are copied byte-for-byte into src/placeCatalog/ (the engine as .cjs,
 * because the MCP package is "type": "module"). A drift test in the MCP suite
 * asserts the copies match.
 *
 * Usage:
 *   node scripts/build-place-catalog.mjs --source /path/to/ne_10m_populated_places_simple.geojson
 *   node scripts/build-place-catalog.mjs --sync-only     # copy engine + data only
 *   node scripts/build-place-catalog.mjs --check         # exit 1 when copies drift
 */
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const WEB_DIR = path.join(ROOT, 'web/profile-viewer');
const MCP_DIR = path.join(ROOT, 'tools/aep-lab-profile-mcp/src/placeCatalog');

const DEFAULT_SOURCE =
  'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_10m_populated_places_simple.geojson';
export const MIN_POPULATION = 10000;

export const COPIES = [
  { from: path.join(WEB_DIR, 'place-catalog.js'), to: path.join(MCP_DIR, 'place-catalog.cjs') },
  { from: path.join(WEB_DIR, 'place-catalog-data.json'), to: path.join(MCP_DIR, 'place-catalog-data.json') },
];

function round4(n) {
  const r = Math.round(Number(n) * 1e4) / 1e4;
  return Object.is(r, -0) ? 0 : r;
}

/**
 * @param {{ features: Array<{ properties: Record<string, unknown> }> }} geojson
 * @returns {{ places: Array<[string, string, number, number, number]>, dropped: number }}
 */
export function extractPlaces(geojson, minPopulation = MIN_POPULATION) {
  const seen = new Set();
  const places = [];
  let dropped = 0;
  for (const feature of geojson.features || []) {
    const p = feature.properties || {};
    const name = String(p.name || '').trim();
    const cc = String(p.iso_a2 || '').trim().toUpperCase();
    const lat = Number(p.latitude);
    const lon = Number(p.longitude);
    const pop = Math.round(Number(p.pop_max));
    const valid = name && /^[A-Z]{2}$/.test(cc) && Number.isFinite(lat) && Math.abs(lat) <= 90
      && Number.isFinite(lon) && Math.abs(lon) <= 180 && Number.isFinite(pop) && pop >= minPopulation;
    if (!valid) {
      dropped += 1;
      continue;
    }
    const row = [name, cc, round4(lat), round4(lon), pop];
    const key = row.slice(0, 4).join('|');
    if (seen.has(key)) continue;
    seen.add(key);
    places.push(row);
  }
  places.sort((a, b) => b[4] - a[4] || a[0].localeCompare(b[0]) || a[1].localeCompare(b[1]));
  return { places, dropped };
}

export function buildDataDocument(places) {
  return {
    version: `natural-earth-10m-populated-places-pop${MIN_POPULATION / 1000}k`,
    source: 'Natural Earth 1:10m Cultural Vectors — Populated Places (simple)',
    sourceUrl: 'https://www.naturalearthdata.com/downloads/10m-cultural-vectors/10m-populated-places/',
    license: 'Public domain (Natural Earth). No attribution required.',
    minPopulation: MIN_POPULATION,
    fields: ['name', 'countryCode', 'latitude', 'longitude', 'population'],
    count: places.length,
    places,
  };
}

function serializeData(doc) {
  const { places, ...meta } = doc;
  const head = JSON.stringify(meta, null, 2).replace(/\n}$/, '');
  const rows = places.map((row) => `    ${JSON.stringify(row)}`).join(',\n');
  return `${head},\n  "places": [\n${rows}\n  ]\n}\n`;
}

function browserWrapper(json) {
  return '/* Generated by scripts/build-place-catalog.mjs — do not edit. Natural Earth, public domain. */\n'
    + "(typeof self !== 'undefined' ? self : this).AepPlaceCatalogData = "
    + `${json.trimEnd()};\n`;
}

async function loadSource(source) {
  if (/^https?:\/\//.test(source)) {
    const res = await fetch(source);
    if (!res.ok) throw new Error(`Download failed: ${res.status} ${res.statusText} for ${source}`);
    return res.json();
  }
  return JSON.parse(await readFile(source, 'utf8'));
}

async function syncCopies() {
  await mkdir(MCP_DIR, { recursive: true });
  for (const { from, to } of COPIES) {
    await writeFile(to, await readFile(from));
  }
}

async function checkCopies() {
  const drift = [];
  for (const { from, to } of COPIES) {
    const [a, b] = await Promise.all([readFile(from), readFile(to).catch(() => null)]);
    if (!b || !a.equals(b)) drift.push(path.relative(ROOT, to));
  }
  return drift;
}

async function main(argv) {
  const args = new Set(argv);
  if (args.has('--check')) {
    const drift = await checkCopies();
    if (drift.length) {
      console.error(`Place catalog copies drifted: ${drift.join(', ')}. Run: npm run build:place-catalog -- --sync-only`);
      process.exit(1);
    }
    console.log('Place catalog copies match.');
    return;
  }
  if (!args.has('--sync-only')) {
    const i = argv.indexOf('--source');
    const source = i >= 0 ? argv[i + 1] : DEFAULT_SOURCE;
    const { places, dropped } = extractPlaces(await loadSource(source));
    const json = serializeData(buildDataDocument(places));
    await writeFile(path.join(WEB_DIR, 'place-catalog-data.json'), json);
    await writeFile(path.join(WEB_DIR, 'place-catalog-data.js'), browserWrapper(json));
    const countries = new Set(places.map((p) => p[1])).size;
    console.log(`Wrote ${places.length} places across ${countries} countries (dropped ${dropped}).`);
  }
  await syncCopies();
  console.log(`Synced engine + data to ${path.relative(ROOT, MCP_DIR)}/`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main(process.argv.slice(2)).catch((err) => {
    console.error(err.message || err);
    process.exit(1);
  });
}
