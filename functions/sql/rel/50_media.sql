CREATE DYNAMIC TABLE IF NOT EXISTS REL.REL_MEDIA_SUBSCRIPTION
  TARGET_LAG = '1 minute' WAREHOUSE = {{WAREHOUSE}}
AS
SELECT
  CONCAT(r.RECIPIENT_ID, '-SUB-001') AS SUBSCRIPTION_ID,
  r.RECIPIENT_ID,
  c.SUBSCRIPTIONTIER AS PLAN,
  TRY_TO_DATE(c.SUBSCRIPTIONSTARTDATE) AS START_DATE,
  DATEADD(day, 365, TRY_TO_DATE(c.SUBSCRIPTIONSTARTDATE)) AS RENEWAL_DATE,
  c.MONTHLYFEE,
  c.PRIMARYGENRE,
  c.PREFERREDDEVICE,
  c.ACCOUNTSHARING,
  'media' AS INDUSTRY,
  COALESCE(TRY_TO_TIMESTAMP_NTZ(TO_VARCHAR(c._RECORDUPDATEDTIMESTAMP)), TRY_TO_TIMESTAMP_NTZ(TO_VARCHAR(c._RECORDCREATEDTIMESTAMP)), r.VERSION_TS) AS VERSION_TS,
  COALESCE(TRY_TO_TIMESTAMP_NTZ(TO_VARCHAR(c._RECORDCREATEDTIMESTAMP)), r.VERSION_TS) AS _RECORDCREATEDTIMESTAMP,
  COALESCE(TRY_TO_TIMESTAMP_NTZ(TO_VARCHAR(c._RECORDUPDATEDTIMESTAMP)), TRY_TO_TIMESTAMP_NTZ(TO_VARCHAR(c._RECORDCREATEDTIMESTAMP)), r.VERSION_TS) AS _RECORDUPDATEDTIMESTAMP,
  c.TESTPROFILE
FROM AEP_SCHEMA.AGENTIC_MEDIA_PROFILE_CUSTOMER c
JOIN REL.RECIPIENT r ON r.ECID = c.ECID;

CREATE DYNAMIC TABLE IF NOT EXISTS REL.REL_MEDIA_VIEWING
  TARGET_LAG = '1 minute' WAREHOUSE = {{WAREHOUSE}}
AS
SELECT
  e.EVENTID AS VIEWING_ID,
  r.RECIPIENT_ID,
  e.CONTENT_ID,
  e.TITLE,
  e.GENRE,
  e.DURATION_WATCHED_MINUTES AS MINUTES_VIEWED,
  TRY_TO_TIMESTAMP_NTZ(TO_VARCHAR(e.TIMESTAMP)) AS VIEWED_AT,
  e.DEVICE,
  'media' AS INDUSTRY,
  COALESCE(TRY_TO_TIMESTAMP_NTZ(TO_VARCHAR(e._RECORDCREATEDTIMESTAMP)), r.VERSION_TS) AS VERSION_TS,
  COALESCE(TRY_TO_TIMESTAMP_NTZ(TO_VARCHAR(e._RECORDCREATEDTIMESTAMP)), r.VERSION_TS) AS _RECORDCREATEDTIMESTAMP,
  COALESCE(TRY_TO_TIMESTAMP_NTZ(TO_VARCHAR(e._RECORDCREATEDTIMESTAMP)), r.VERSION_TS) AS _RECORDUPDATEDTIMESTAMP,
  TRUE AS TESTPROFILE
FROM AEP_SCHEMA.AGENTIC_MEDIA_EVENT_VIEWING e
JOIN REL.RECIPIENT r ON r.ECID = e.ECID;

CREATE DYNAMIC TABLE IF NOT EXISTS REL.REL_MEDIA_TITLE_CATALOG
  TARGET_LAG = '1 minute' WAREHOUSE = {{WAREHOUSE}}
AS
SELECT
  e.CONTENT_ID AS TITLE_ID,
  MAX(e.TITLE) AS TITLE,
  MAX(e.GENRE) AS GENRE,
  MAX(e.CONTENT_TYPE) AS CONTENT_TYPE,
  MAX(TRY_TO_TIMESTAMP_NTZ(TO_VARCHAR(e._RECORDCREATEDTIMESTAMP))) AS VERSION_TS,
  MAX(TRY_TO_TIMESTAMP_NTZ(TO_VARCHAR(e._RECORDCREATEDTIMESTAMP))) AS _RECORDCREATEDTIMESTAMP,
  MAX(TRY_TO_TIMESTAMP_NTZ(TO_VARCHAR(e._RECORDCREATEDTIMESTAMP))) AS _RECORDUPDATEDTIMESTAMP,
  TRUE AS TESTPROFILE,
  'media' AS INDUSTRY
FROM AEP_SCHEMA.AGENTIC_MEDIA_EVENT_VIEWING e
GROUP BY e.CONTENT_ID;
