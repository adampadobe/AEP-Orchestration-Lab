CREATE DYNAMIC TABLE IF NOT EXISTS REL.REL_RETAIL_REWARDS
  TARGET_LAG = '1 minute' WAREHOUSE = {{WAREHOUSE}}
AS
SELECT
  CONCAT(r.RECIPIENT_ID, '-REW-001') AS REWARDS_ID,
  r.RECIPIENT_ID,
  e.TIER,
  e.POINTS_BALANCE,
  e.POINTS_EARNED_YTD,
  e.POINTS_REDEEMED_YTD,
  TRY_TO_DATE(e.TIER_EXPIRY_DATE) AS TIER_EXPIRY_DATE,
  e.NEXT_TIER_THRESHOLD,
  e.PREFERRED_REWARD_TYPE,
  'retail' AS INDUSTRY,
  COALESCE(TRY_TO_TIMESTAMP_NTZ(TO_VARCHAR(e._RECORDCREATEDTIMESTAMP)), r.VERSION_TS) AS VERSION_TS,
  COALESCE(TRY_TO_TIMESTAMP_NTZ(TO_VARCHAR(e._RECORDCREATEDTIMESTAMP)), r.VERSION_TS) AS _RECORDCREATEDTIMESTAMP,
  COALESCE(TRY_TO_TIMESTAMP_NTZ(TO_VARCHAR(e._RECORDCREATEDTIMESTAMP)), r.VERSION_TS) AS _RECORDUPDATEDTIMESTAMP,
  r.TESTPROFILE
FROM AEP_SCHEMA.AGENTIC_RETAIL_PROFILE_REWARDS e
JOIN REL.RECIPIENT r ON r.ECID = e.ECID;

CREATE DYNAMIC TABLE IF NOT EXISTS REL.REL_RETAIL_PRODUCT_CATALOG
  TARGET_LAG = '1 minute' WAREHOUSE = {{WAREHOUSE}}
AS
SELECT
  item.VALUE:sku::VARCHAR AS SKU,
  MAX(item.VALUE:name::VARCHAR) AS PRODUCT_NAME,
  MAX(item.VALUE:category::VARCHAR) AS CATEGORY,
  MAX(item.VALUE:price::NUMBER(12,2)) AS PRICE,
  'retail' AS INDUSTRY,
  MAX(TRY_TO_TIMESTAMP_NTZ(TO_VARCHAR(e._RECORDCREATEDTIMESTAMP))) AS VERSION_TS,
  MAX(TRY_TO_TIMESTAMP_NTZ(TO_VARCHAR(e._RECORDCREATEDTIMESTAMP))) AS _RECORDCREATEDTIMESTAMP,
  MAX(TRY_TO_TIMESTAMP_NTZ(TO_VARCHAR(e._RECORDCREATEDTIMESTAMP))) AS _RECORDUPDATEDTIMESTAMP,
  TRUE AS TESTPROFILE
FROM AEP_SCHEMA.AGENTIC_RETAIL_EVENT_ORDER e,
LATERAL FLATTEN(INPUT => e.ITEMS) item
GROUP BY item.VALUE:sku::VARCHAR;
