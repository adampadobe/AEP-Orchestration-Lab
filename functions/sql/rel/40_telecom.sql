CREATE DYNAMIC TABLE IF NOT EXISTS REL.REL_TELECOM_SUBSCRIPTION
  TARGET_LAG = '1 minute' WAREHOUSE = {{WAREHOUSE}}
AS
SELECT
  CONCAT(r.RECIPIENT_ID, '-SUB-001') AS SUBSCRIPTION_ID,
  r.RECIPIENT_ID,
  c.PLANTIER AS PLAN,
  c.BUNDLETYPE AS BUNDLE,
  TRY_TO_DATE(c.CONTRACTSTARTDATE) AS CONTRACT_START_DATE,
  TRY_TO_DATE(c.CONTRACTENDDATE) AS CONTRACT_END_DATE,
  c.MONTHLYSPEND,
  c.DATAALLOWANCEGB,
  c.UPGRADEELIGIBLE AS UPGRADE_ELIGIBLE,
  'telecom' AS INDUSTRY,
  COALESCE(TRY_TO_TIMESTAMP_NTZ(TO_VARCHAR(c._RECORDCREATEDTIMESTAMP)), r.VERSION_TS) AS VERSION_TS,
  COALESCE(TRY_TO_TIMESTAMP_NTZ(TO_VARCHAR(c._RECORDCREATEDTIMESTAMP)), r.VERSION_TS) AS _RECORDCREATEDTIMESTAMP,
  COALESCE(TRY_TO_TIMESTAMP_NTZ(TO_VARCHAR(c._RECORDCREATEDTIMESTAMP)), r.VERSION_TS) AS _RECORDUPDATEDTIMESTAMP,
  c.TESTPROFILE
FROM AEP_SCHEMA.AGENTIC_TELECOM_PROFILE_CUSTOMER c
JOIN REL.RECIPIENT r ON r.ECID = c.ECID;

CREATE DYNAMIC TABLE IF NOT EXISTS REL.REL_TELECOM_DEVICE
  TARGET_LAG = '1 minute' WAREHOUSE = {{WAREHOUSE}}
AS
SELECT
  CONCAT(r.RECIPIENT_ID, '-DEVICE-', COALESCE(d.IMEI, '001')) AS DEVICE_ID,
  r.RECIPIENT_ID,
  d.DEVICE_MODEL AS MODEL,
  d.IMEI,
  TRY_TO_DATE(d.ACTIVATION_DATE) AS ACTIVATION_DATE,
  d.TRADE_IN_VALUE,
  d.INSURANCE,
  d.INSURANCE_TIER,
  TRY_TO_DATE(d.UPGRADE_ELIGIBLE_DATE) AS UPGRADE_ELIGIBLE_DATE,
  d.PREVIOUS_DEVICE,
  d.CONTRACT_MONTHS,
  d.STATUS,
  'telecom' AS INDUSTRY,
  COALESCE(TRY_TO_TIMESTAMP_NTZ(TO_VARCHAR(d._RECORDCREATEDTIMESTAMP)), r.VERSION_TS) AS VERSION_TS,
  COALESCE(TRY_TO_TIMESTAMP_NTZ(TO_VARCHAR(d._RECORDCREATEDTIMESTAMP)), r.VERSION_TS) AS _RECORDCREATEDTIMESTAMP,
  COALESCE(TRY_TO_TIMESTAMP_NTZ(TO_VARCHAR(d._RECORDCREATEDTIMESTAMP)), r.VERSION_TS) AS _RECORDUPDATEDTIMESTAMP,
  TRUE AS TESTPROFILE
FROM AEP_SCHEMA.AGENTIC_TELECOM_PROFILE_DEVICES d
JOIN REL.RECIPIENT r ON r.ECID = d.ECID;

CREATE DYNAMIC TABLE IF NOT EXISTS REL.REL_TELECOM_PLAN_CATALOG
  TARGET_LAG = '1 minute' WAREHOUSE = {{WAREHOUSE}}
AS
SELECT
  UPPER(c.PLANTIER) AS PLAN_CODE,
  INITCAP(REPLACE(c.PLANTIER, '_', ' ')) AS PLAN_NAME,
  c.BUNDLETYPE AS BUNDLE,
  c.DATAALLOWANCEGB,
  MIN(c.MONTHLYSPEND) AS PRICE_FROM,
  MAX(c.MONTHLYSPEND) AS PRICE_TO,
  'GBP' AS CURRENCY,
  'telecom' AS INDUSTRY,
  MAX(TRY_TO_TIMESTAMP_NTZ(TO_VARCHAR(c._RECORDCREATEDTIMESTAMP))) AS VERSION_TS,
  MAX(TRY_TO_TIMESTAMP_NTZ(TO_VARCHAR(c._RECORDCREATEDTIMESTAMP))) AS _RECORDCREATEDTIMESTAMP,
  MAX(TRY_TO_TIMESTAMP_NTZ(TO_VARCHAR(c._RECORDCREATEDTIMESTAMP))) AS _RECORDUPDATEDTIMESTAMP,
  TRUE AS TESTPROFILE
FROM AEP_SCHEMA.AGENTIC_TELECOM_PROFILE_CUSTOMER c
GROUP BY UPPER(c.PLANTIER), INITCAP(REPLACE(c.PLANTIER, '_', ' ')), c.BUNDLETYPE, c.DATAALLOWANCEGB;
