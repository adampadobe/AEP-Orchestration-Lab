-- Travel foreign-key integrity. Each result should be zero.
SELECT 'segment_without_reservation' AS CHECK_NAME, COUNT_IF(r.RESERVATION_ID IS NULL) AS FAILURE_COUNT
FROM REL.REL_TRAVEL_FLIGHT_SEGMENT s
LEFT JOIN REL.REL_TRAVEL_RESERVATION r
  ON r.RESERVATION_ID = s.RESERVATION_ID AND r.RECIPIENT_ID = s.RECIPIENT_ID
UNION ALL
SELECT 'passenger_without_reservation', COUNT_IF(r.RESERVATION_ID IS NULL)
FROM REL.REL_TRAVEL_PASSENGER p
LEFT JOIN REL.REL_TRAVEL_RESERVATION r
  ON r.RESERVATION_ID = p.RESERVATION_ID
UNION ALL
SELECT 'ancillary_without_segment_or_passenger', COUNT_IF(s.SEGMENT_ID IS NULL OR p.PASSENGER_ID IS NULL)
FROM REL.REL_TRAVEL_ANCILLARY_PURCHASE a
LEFT JOIN REL.REL_TRAVEL_FLIGHT_SEGMENT s ON s.SEGMENT_ID = a.SEGMENT_ID
LEFT JOIN REL.REL_TRAVEL_PASSENGER p ON p.PASSENGER_ID = a.PASSENGER_ID
UNION ALL
SELECT 'ancillary_without_catalog_item', COUNT_IF(c.PRODUCT_CODE IS NULL)
FROM REL.REL_TRAVEL_ANCILLARY_PURCHASE a
LEFT JOIN REL.REL_TRAVEL_PRODUCT_CATALOG c ON c.PRODUCT_CODE = a.PRODUCT_CODE;

-- Booking payloads must agree with the relational reservation's PNR and
-- outbound segment. Both result counts should be zero.
SELECT 'booking_event_missing' AS CHECK_NAME, COUNT_IF(b._ID IS NULL) AS FAILURE_COUNT
FROM REL.REL_TRAVEL_RESERVATION r
JOIN REL.RECIPIENT p ON p.RECIPIENT_ID = r.RECIPIENT_ID
JOIN REL.REL_TRAVEL_FLIGHT_SEGMENT s
  ON s.RESERVATION_ID = r.RESERVATION_ID AND s.SEGMENT_ID LIKE '%-SEG-001'
LEFT JOIN AEP_SCHEMA.AGENTIC_TRAVEL_EVENT_BOOKING b
  ON b.ECID = p.ECID AND b.PNR = r.PNR_LOCATOR
UNION ALL
SELECT 'booking_event_mismatch', COUNT_IF(
  b.OUTBOUNDFLIGHTNUMBER IS DISTINCT FROM s.FLIGHT_NUMBER
  OR TRY_TO_TIMESTAMP_NTZ(TO_VARCHAR(b.OUTBOUNDDEPARTUREDATE)) IS DISTINCT FROM s.DEPARTURE_UTC
)
FROM REL.REL_TRAVEL_RESERVATION r
JOIN REL.RECIPIENT p ON p.RECIPIENT_ID = r.RECIPIENT_ID
JOIN REL.REL_TRAVEL_FLIGHT_SEGMENT s
  ON s.RESERVATION_ID = r.RESERVATION_ID AND s.SEGMENT_ID LIKE '%-SEG-001'
JOIN AEP_SCHEMA.AGENTIC_TRAVEL_EVENT_BOOKING b
  ON b.ECID = p.ECID AND b.PNR = r.PNR_LOCATOR;

-- Every generated disruption must point at a real flight segment.
SELECT COUNT(*) AS ORPHAN_DISRUPTION_SEGMENTS
FROM AEP_SCHEMA.AGENTIC_TRAVEL_EVENT_DISRUPTION d
LEFT JOIN REL.REL_TRAVEL_FLIGHT_SEGMENT s ON s.SEGMENT_ID = d.SEGMENT_ID
WHERE d.SEGMENT_ID IS NOT NULL AND s.SEGMENT_ID IS NULL;

