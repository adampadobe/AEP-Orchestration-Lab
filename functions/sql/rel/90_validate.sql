-- Read-only validation queries. Run after the relational generator and allow
-- dynamic tables time to refresh. TARGET_LAG is a target, not a deadline.

-- Duplicate deterministic recipient keys; expect zero rows.
SELECT RECIPIENT_ID, COUNT(*) AS ROW_COUNT
FROM REL.RECIPIENT
WHERE RECIPIENT_ID IS NOT NULL
GROUP BY RECIPIENT_ID
HAVING COUNT(*) > 1;

-- Historical base rows without ECIDs need identity remediation before linking.
SELECT COUNT(*) AS MISSING_RECIPIENT_ID
FROM REL.RECIPIENT
WHERE RECIPIENT_ID IS NULL;

-- Recipients with missing channel preference or a preferred channel they did
-- not consent to. Expect zero rows after generation.
SELECT RECIPIENT_ID, INDUSTRY, PREFERREDCHANNEL,
  CONSENT_EMAIL, CONSENT_SMS, CONSENT_WHATSAPP, CONSENT_PUSH
FROM REL.RECIPIENT
WHERE VERSION_TS IS NOT NULL AND (
   (PREFERREDCHANNEL IS NULL AND 'y' IN (CONSENT_EMAIL, CONSENT_SMS, CONSENT_WHATSAPP, CONSENT_PUSH))
   OR (PREFERREDCHANNEL = 'email' AND CONSENT_EMAIL <> 'y')
   OR (PREFERREDCHANNEL = 'sms' AND CONSENT_SMS <> 'y')
   OR (PREFERREDCHANNEL = 'whatsapp' AND CONSENT_WHATSAPP <> 'y')
   OR (PREFERREDCHANNEL = 'push' AND CONSENT_PUSH <> 'y'));

