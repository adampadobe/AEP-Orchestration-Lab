CREATE DYNAMIC TABLE IF NOT EXISTS REL.REL_SPORTS_MEMBERSHIP
  TARGET_LAG = '1 minute' WAREHOUSE = {{WAREHOUSE}}
AS
SELECT
  CONCAT(r.RECIPIENT_ID, '-MEM-001') AS MEMBERSHIP_ID,
  r.RECIPIENT_ID,
  e.MEMBERSHIP_TYPE,
  TRY_TO_DATE(e.MEMBER_SINCE) AS MEMBER_SINCE,
  TRY_TO_DATE(e.RENEWAL_DATE) AS RENEWAL_DATE,
  e.AUTO_RENEW,
  e.ANNUAL_FEE,
  e.LOYALTY_POINTS,
  e.REFERRALS_MADE,
  e.STATUS,
  'sports' AS INDUSTRY,
  COALESCE(TRY_TO_TIMESTAMP_NTZ(TO_VARCHAR(e._RECORDCREATEDTIMESTAMP)), r.VERSION_TS) AS VERSION_TS,
  COALESCE(TRY_TO_TIMESTAMP_NTZ(TO_VARCHAR(e._RECORDCREATEDTIMESTAMP)), r.VERSION_TS) AS _RECORDCREATEDTIMESTAMP,
  COALESCE(TRY_TO_TIMESTAMP_NTZ(TO_VARCHAR(e._RECORDCREATEDTIMESTAMP)), r.VERSION_TS) AS _RECORDUPDATEDTIMESTAMP,
  TRUE AS TESTPROFILE
FROM AEP_SCHEMA.AGENTIC_SPORTS_PROFILE_MEMBERSHIP e
JOIN REL.RECIPIENT r ON r.ECID = e.ECID;

CREATE DYNAMIC TABLE IF NOT EXISTS REL.REL_SPORTS_TICKET
  TARGET_LAG = '1 minute' WAREHOUSE = {{WAREHOUSE}}
AS
SELECT
  COALESCE(e.EVENTID, e.EVENT_ID) AS TICKET_ID,
  r.RECIPIENT_ID,
  COALESCE(e.EVENT_ID, e.EVENTID) AS FIXTURE_ID,
  e.EVENT_NAME,
  e.SPORT,
  e.VENUE,
  e.SECTION,
  e.TICKET_TYPE,
  e.TICKET_PRICE,
  TRY_TO_TIMESTAMP_NTZ(TO_VARCHAR(e.GATE_SCAN_TIME)) AS EVENT_TS,
  'sports' AS INDUSTRY,
  COALESCE(TRY_TO_TIMESTAMP_NTZ(TO_VARCHAR(e._RECORDCREATEDTIMESTAMP)), r.VERSION_TS) AS VERSION_TS,
  COALESCE(TRY_TO_TIMESTAMP_NTZ(TO_VARCHAR(e._RECORDCREATEDTIMESTAMP)), r.VERSION_TS) AS _RECORDCREATEDTIMESTAMP,
  COALESCE(TRY_TO_TIMESTAMP_NTZ(TO_VARCHAR(e._RECORDCREATEDTIMESTAMP)), r.VERSION_TS) AS _RECORDUPDATEDTIMESTAMP,
  TRUE AS TESTPROFILE
FROM AEP_SCHEMA.AGENTIC_SPORTS_EVENT_ATTENDANCE e
JOIN REL.RECIPIENT r ON r.ECID = e.ECID;

CREATE DYNAMIC TABLE IF NOT EXISTS REL.REL_SPORTS_MERCH_ORDER
  TARGET_LAG = '1 minute' WAREHOUSE = {{WAREHOUSE}}
AS
SELECT
  COALESCE(e.ORDER_ID, e.EVENTID) AS ORDER_ID,
  r.RECIPIENT_ID,
  e.TIMESTAMP AS ORDER_TS,
  e.ITEM_COUNT,
  e.ORDER_TOTAL,
  e.CURRENCY,
  e.CHANNEL,
  e.PAYMENT_METHOD,
  e.PERSONALISATION,
  'sports' AS INDUSTRY,
  COALESCE(TRY_TO_TIMESTAMP_NTZ(TO_VARCHAR(e._RECORDCREATEDTIMESTAMP)), r.VERSION_TS) AS VERSION_TS,
  COALESCE(TRY_TO_TIMESTAMP_NTZ(TO_VARCHAR(e._RECORDCREATEDTIMESTAMP)), r.VERSION_TS) AS _RECORDCREATEDTIMESTAMP,
  COALESCE(TRY_TO_TIMESTAMP_NTZ(TO_VARCHAR(e._RECORDCREATEDTIMESTAMP)), r.VERSION_TS) AS _RECORDUPDATEDTIMESTAMP,
  TRUE AS TESTPROFILE
FROM AEP_SCHEMA.AGENTIC_SPORTS_EVENT_MERCHANDISE e
JOIN REL.RECIPIENT r ON r.ECID = e.ECID;

CREATE DYNAMIC TABLE IF NOT EXISTS REL.REL_SPORTS_MERCH_ORDER_LINE
  TARGET_LAG = '1 minute' WAREHOUSE = {{WAREHOUSE}}
AS
SELECT
  CONCAT(COALESCE(e.ORDER_ID, e.EVENTID), '-LINE-', LPAD(TO_VARCHAR(item.INDEX), 3, '0')) AS ORDER_LINE_ID,
  COALESCE(e.ORDER_ID, e.EVENTID) AS ORDER_ID,
  r.RECIPIENT_ID,
  item.VALUE:sku::VARCHAR AS SKU,
  item.VALUE:name::VARCHAR AS PRODUCT_NAME,
  item.VALUE:qty::NUMBER(10,0) AS QUANTITY,
  item.VALUE:price::NUMBER(12,2) AS UNIT_PRICE,
  'sports' AS INDUSTRY,
  COALESCE(TRY_TO_TIMESTAMP_NTZ(TO_VARCHAR(e._RECORDCREATEDTIMESTAMP)), r.VERSION_TS) AS VERSION_TS,
  COALESCE(TRY_TO_TIMESTAMP_NTZ(TO_VARCHAR(e._RECORDCREATEDTIMESTAMP)), r.VERSION_TS) AS _RECORDCREATEDTIMESTAMP,
  COALESCE(TRY_TO_TIMESTAMP_NTZ(TO_VARCHAR(e._RECORDCREATEDTIMESTAMP)), r.VERSION_TS) AS _RECORDUPDATEDTIMESTAMP,
  TRUE AS TESTPROFILE
FROM AEP_SCHEMA.AGENTIC_SPORTS_EVENT_MERCHANDISE e,
LATERAL FLATTEN(INPUT => e.ITEMS) item,
REL.RECIPIENT r
WHERE r.ECID = e.ECID;

CREATE TABLE IF NOT EXISTS REL.REL_SPORTS_EVENT_CATALOG (
  EVENT_ID VARCHAR(64) NOT NULL,
  EVENT_NAME VARCHAR(160),
  SPORT VARCHAR(32),
  VENUE VARCHAR(100),
  EVENT_DATE DATE NOT NULL,
  SECTION VARCHAR(64),
  TICKET_TYPE VARCHAR(32),
  PRICE_FROM NUMBER(12,2),
  VERSION_TS TIMESTAMP_NTZ NOT NULL,
  _RECORDCREATEDTIMESTAMP TIMESTAMP_NTZ NOT NULL,
  _RECORDUPDATEDTIMESTAMP TIMESTAMP_NTZ NOT NULL,
  TESTPROFILE BOOLEAN NOT NULL,
  INDUSTRY VARCHAR(32) NOT NULL,
  CONSTRAINT PK_REL_SPORTS_EVENT_CATALOG PRIMARY KEY (EVENT_ID)
);
