CREATE DYNAMIC TABLE IF NOT EXISTS REL.REL_FSI_ACCOUNT
  TARGET_LAG = '1 minute' WAREHOUSE = {{WAREHOUSE}}
AS
SELECT
  CONCAT(r.RECIPIENT_ID, '-ACC-', COALESCE(p.ACCOUNT_NUMBER, '001')) AS ACCOUNT_ID,
  r.RECIPIENT_ID,
  p.ACCOUNT_NUMBER,
  p.PRODUCT_TYPE AS ACCOUNT_TYPE,
  p.OPEN_DATE,
  p.BALANCE,
  p.INTEREST_RATE,
  p.TERM_END_DATE,
  c.NEXTRATERENEWDATE AS RATE_RENEWAL_DATE,
  p.MONTHLY_PAYMENT,
  p.STATUS,
  'fsi' AS INDUSTRY,
  COALESCE(TRY_TO_TIMESTAMP_NTZ(TO_VARCHAR(p._RECORDCREATEDTIMESTAMP)), r.VERSION_TS) AS VERSION_TS,
  COALESCE(TRY_TO_TIMESTAMP_NTZ(TO_VARCHAR(p._RECORDCREATEDTIMESTAMP)), r.VERSION_TS) AS _RECORDCREATEDTIMESTAMP,
  COALESCE(TRY_TO_TIMESTAMP_NTZ(TO_VARCHAR(p._RECORDCREATEDTIMESTAMP)), r.VERSION_TS) AS _RECORDUPDATEDTIMESTAMP,
  r.TESTPROFILE
FROM AEP_SCHEMA.AGENTIC_FSI_PROFILE_PRODUCTS p
JOIN REL.RECIPIENT r ON r.ECID = p.ECID
LEFT JOIN AEP_SCHEMA.AGENTIC_FSI_PROFILE_CUSTOMER c ON c.ECID = p.ECID
WHERE LOWER(p.PRODUCT_TYPE) IN ('checking', 'savings', 'current_account');

