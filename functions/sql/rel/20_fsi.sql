CREATE DYNAMIC TABLE IF NOT EXISTS REL.REL_FSI_TRANSACTION
  TARGET_LAG = '1 minute' WAREHOUSE = {{WAREHOUSE}}
AS
SELECT
  COALESCE(e.EVENTID, CONCAT(r.RECIPIENT_ID, '-TXN-', TO_VARCHAR(e.TIMESTAMP))) AS TRANSACTION_ID,
  r.RECIPIENT_ID,
  e.TIMESTAMP AS TRANSACTION_TS,
  e.TRANSACTION_TYPE,
  e.DIRECTION,
  e.AMOUNT,
  e.CURRENCY,
  e.MERCHANT,
  e.CATEGORY,
  e.ACCOUNT_TYPE,
  e.REFERENCE,
  'fsi' AS INDUSTRY,
  COALESCE(TRY_TO_TIMESTAMP_NTZ(TO_VARCHAR(e.TIMESTAMP)), r.VERSION_TS) AS VERSION_TS,
  COALESCE(TRY_TO_TIMESTAMP_NTZ(TO_VARCHAR(e._RECORDCREATEDTIMESTAMP)), r.VERSION_TS) AS _RECORDCREATEDTIMESTAMP,
  COALESCE(TRY_TO_TIMESTAMP_NTZ(TO_VARCHAR(e._RECORDCREATEDTIMESTAMP)), r.VERSION_TS) AS _RECORDUPDATEDTIMESTAMP,
  r.TESTPROFILE
FROM AEP_SCHEMA.AGENTIC_FSI_EVENT_TRANSACTION e
JOIN REL.RECIPIENT r ON r.ECID = e.ECID;

CREATE DYNAMIC TABLE IF NOT EXISTS REL.REL_FSI_PRODUCT_CATALOG
  TARGET_LAG = '1 minute' WAREHOUSE = {{WAREHOUSE}}
AS
SELECT
  LOWER(p.PRODUCT_TYPE) AS PRODUCT_CODE,
  INITCAP(REPLACE(LOWER(p.PRODUCT_TYPE), '_', ' ')) AS PRODUCT_NAME,
  LOWER(p.PRODUCT_TYPE) AS PRODUCT_TYPE,
  'fsi' AS INDUSTRY,
  MAX(TRY_TO_TIMESTAMP_NTZ(TO_VARCHAR(p._RECORDCREATEDTIMESTAMP))) AS VERSION_TS,
  MIN(TRY_TO_TIMESTAMP_NTZ(TO_VARCHAR(p._RECORDCREATEDTIMESTAMP))) AS _RECORDCREATEDTIMESTAMP,
  MAX(TRY_TO_TIMESTAMP_NTZ(TO_VARCHAR(p._RECORDCREATEDTIMESTAMP))) AS _RECORDUPDATEDTIMESTAMP,
  TRUE AS TESTPROFILE
FROM AEP_SCHEMA.AGENTIC_FSI_PROFILE_PRODUCTS p
GROUP BY LOWER(p.PRODUCT_TYPE);
